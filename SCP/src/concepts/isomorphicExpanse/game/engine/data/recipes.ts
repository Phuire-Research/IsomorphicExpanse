export function getRecipe(id: string): RecipeDefinition | undefined {
  return RECIPES[id];
}

export function getAvailableRecipes(age: Age, inventory: Record<string, number>, discoveredTechs: string[] = []): RecipeDefinition[] {
  const ageOrder: Age[] = [
    Age.Gathering,
    Age.Stone,
    Age.Wood,
    Age.Clay,
    Age.Copper,
    Age.Iron,
    Age.Steam,
    Age.Electric,
    Age.Chemical,
    Age.Rocket,
  ];
  const currentAgeIndex = ageOrder.indexOf(age);

  return Object.values(RECIPES).filter((recipe) => {
    const recipeAgeIndex = ageOrder.indexOf(recipe.requiredAge);
    if (recipeAgeIndex > currentAgeIndex) {
      return false;
    }

    if (recipe.requiredTech && !discoveredTechs.includes(recipe.requiredTech)) {
      return false;
    }

    for (const [itemId, requiredQty] of Object.entries(recipe.inputs)) {
      if ((inventory[itemId] ?? 0) < requiredQty) {
        return false;
      }
    }

    return true;
  });
}
